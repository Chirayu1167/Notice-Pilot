import { useState } from "react";
import { Card } from "../ui/Card";
import { EmptyState } from "../ui/EmptyState";
import { StatusBadge } from "../ui/StatusBadge";
import type { DraftVersion } from "../../types";
import { CitationText } from "../agent/CitationText";

function versionTone(status?: string): "ok" | "warn" | "err" {
  if (status === "APPROVED") return "ok";
  if (status === "REJECTED") return "err";
  return "warn";
}

function actorLabel(createdBy: string): string {
  if (createdBy === "AGENT") return "Generated by Agent";
  return "Edited by Reviewer";
}

export function VersionHistory({
  versions,
  noticeId,
  selected,
  onSelect,
}: {
  versions: DraftVersion[];
  noticeId: string;
  selected: number;
  onSelect: (version: number) => void;
}) {
  const [viewing, setViewing] = useState<number | null>(null);
  if (versions.length === 0) {
    return (
      <Card title="Version history">
        <EmptyState title="No versions" description="Versions appear after the first draft." />
      </Card>
    );
  }
  const viewed = versions.find((v) => v.version === viewing) ?? null;
  return (
    <Card title="Version history">
      <div className="cb">
        <ul style={{ margin: 0, paddingLeft: 18 }}>
          {versions.map((v) => (
            <li key={v.id} style={{ marginBottom: 6 }}>
              <button
                type="button"
                className="btn"
                style={{ padding: "2px 8px", fontSize: 12 }}
                aria-pressed={selected === v.version}
                onClick={() => {
                  onSelect(v.version);
                  setViewing(null);
                }}
              >
                v{v.version}
              </button>{" "}
              <span className="sub">
                {actorLabel(v.createdBy)} · {v.createdAt ?? "–"}
              </span>{" "}
              <StatusBadge label={v.reviewStatus} tone={versionTone(v.reviewStatus)} />{" "}
              <button
                type="button"
                className="btn"
                style={{ padding: "2px 8px", fontSize: 12 }}
                onClick={() => setViewing(viewing === v.version ? null : v.version)}
              >
                {viewing === v.version ? "Hide" : "View version"}
              </button>
            </li>
          ))}
        </ul>
        {viewed ? (
          <div style={{ marginTop: 8, borderTop: "1px solid var(--border, #ddd)", paddingTop: 8 }}>
            <b>
              v{viewed.version} (immutable)
            </b>
            <div style={{ whiteSpace: "pre-wrap", marginTop: 4 }}>
              <CitationText text={viewed.content} noticeId={noticeId} />
            </div>
          </div>
        ) : null}
      </div>
    </Card>
  );
}
